print("[2] clutching: the bundle on S^2 glued along the equator by z -> z^k")
def wn(f, M=4096):
    z = np.exp(2j * np.pi * np.arange(M) / M); w = f(z)
    return round(float(np.angle(np.roll(w, -1) / w).sum() / (2 * np.pi)))
deg = {k: wn(lambda z, k=k: z ** k) for k in range(-3, 4)}
check("the clutching function z^k has winding number k, k = -3..3 (the degree, i.e. first Chern number, of the bundle)",
      all(deg[k] == k for k in deg), str(deg))
check("Zois' generator b is z -> 1/z: winding number -1", wn(lambda z: 1 / z) == -1)
pairs = [(a, b) for a in range(-2, 3) for b in range(-2, 3)]
check("tensor product multiplies clutching functions, and the degrees add: wn(z^a z^b) = a + b for all 25 pairs",
      all(wn(lambda z, a=a, b=b: z ** a * z ** b) == a + b for a, b in pairs))
f = lambda z: (z - 0.3) * (z + 0.2j) / (z - 3)

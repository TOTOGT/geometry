check("real Cl_0,n: centre R for n even; for n odd, C when n = 1 mod 4 and R+R when n = 3 mod 4 (period 4)",
      all(r[2] == ("R" if r[0] % 2 == 0 else ("C" if r[0] % 4 == 1 else "R+R")) for r in rows))
check("the pattern of centres repeats every 4 for n = 0..16", all(rows[n][2] == rows[n + 4][2] for n in range(13)))


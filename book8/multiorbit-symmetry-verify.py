head(2, "THE ORBIT IS A RECTANGLE, NOT THREE FREE POINTS")
print('  Two orthogonal mirrors through a common point c, with unit normals u, v,')
print('  u.v = 0. The orbit of p is {p, R_u p, R_v p, R_u R_v p}, and writing')
print('  a = (p - c).u, b = (p - c).v, those four points are')
print('      c + a u + b v + w,   c - a u + b v + w,')
print('      c + a u - b v + w,   c - a u - b v + w      (w the common remainder)')
print('  i.e. the four corners of a rectangle with sides 2|a| and 2|b|.\n')

def reflect(p, c, n):
    d = sum((p[i] - c[i]) * n[i] for i in range(len(p)))
    return tuple(p[i] - 2.0 * d * n[i] for i in range(len(p)))

def ang(a, b, c):
    """angle at b, in degrees"""
    u = [a[i] - b[i] for i in range(len(a))]
    v = [c[i] - b[i] for i in range(len(a))]
    nu = math.sqrt(sum(x * x for x in u)); nv = math.sqrt(sum(x * x for x in v))
    dot = sum(u[i] * v[i] for i in range(len(u))) / (nu * nv)
    return math.degrees(math.acos(max(-1.0, min(1.0, dot))))

random.seed(4)
worst = 0.0
for _ in range(400):
    th = random.uniform(0, math.pi)
    u = (math.cos(th), math.sin(th))
    v = (-math.sin(th), math.cos(th))
    c = (random.uniform(-5, 5), random.uniform(-5, 5))
    p = (random.uniform(-5, 5), random.uniform(-5, 5))
    q = [p, reflect(p, c, u), reflect(p, c, v), reflect(reflect(p, c, u), c, v)]
    # in a rectangle, the angle at every corner is 90 degrees
    for i in range(4):
        others = [x for j, x in enumerate(q) if j != i]
        # the two adjacent corners are the two nearest
        others.sort(key=lambda x: sum((x[k] - q[i][k]) ** 2 for k in range(2)))
        worst = max(worst, abs(ang(others[0], q[i], others[1]) - 90.0))
check(worst < 1e-9, 'on 400 random mirror pairs and random points, every corner '
      'of the orbit is a right angle', 'worst deviation %.3e deg' % worst)

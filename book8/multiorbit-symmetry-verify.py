print('  Three points are three corners of SOME rectangle iff one of the three')
print('  angles of their triangle is 90 degrees. The test returns the angle')
print('  closest to 90 and the vertex it sits at.\n')

def rect_test(P, names):
    best = None
    for i in range(3):
        j, k = [x for x in range(3) if x != i]
        a = ang(P[j], P[i], P[k])
        if best is None or abs(a - 90.0) < abs(best[0] - 90.0):
            best = (a, names[i])
    return best

def fourth_corner(P, i):
    """the missing corner, given that the right angle is at P[i]"""
    j, k = [x for x in range(3) if x != i]
    return tuple(P[j][d] + P[k][d] - P[i][d] for d in range(len(P[0])))

# fixture A: an exact rectangle, one corner removed -> must read 90
A = [(0.0, 0.0), (3.0, 0.0), (0.0, 2.0)]
a, v = rect_test(A, ['a', 'b', 'c'])
check(abs(a - 90.0) < 1e-12, 'fixture A (three corners of a 3x2 rectangle) '
      'reads 90.000000 at the right vertex', '%.9f at %s' % (a, v))
f = fourth_corner(A, 0)
check(abs(f[0] - 3.0) < 1e-12 and abs(f[1] - 2.0) < 1e-12,
      'and the predicted fourth corner is (3, 2)', str(f))
# fixture B: equilateral -> must read 60, far from 90
B = [(0.0, 0.0), (1.0, 0.0), (0.5, math.sqrt(3) / 2)]
b, _ = rect_test(B, ['a', 'b', 'c'])
check(abs(b - 60.0) < 1e-12, 'fixture B (equilateral) reads 60.000000, so the '
      'test is not vacuous', '%.9f' % b)
# fixture C: collinear -> degenerate, must not read 90
